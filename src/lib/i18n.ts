export function getTranslation(lang: Language, key: keyof typeof translations['ru'], ...args: (string | number)[]): string {
  let text = translations[lang]?.[key] || translations['ru'][key] || String(key);
  args.forEach((arg, index) => {
    text = text.replace(new RegExp(`\\{${index}\\}`, 'g'), String(arg));
  });
  return text;
}
